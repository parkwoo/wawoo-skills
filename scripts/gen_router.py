#!/usr/bin/env python3
"""Generate ROUTER.md — the intent→workflow routing table (for Kilo instructions).

Reads the WORKFLOWS in `mcp/intent_catalog.py` and the `.kilo/commands/*.md` frontmatter as
the only inputs, and outputs a short table to put in the agent context every time.
Output defaults to the global config directory ($KILO_GLOBAL_DIR or ~/.config/kilo).

Usage:
  python3 scripts/gen_router.py                     # write to the default output
  python3 scripts/gen_router.py --out /path/ROUTER.md
  python3 scripts/gen_router.py --print             # stdout only
"""
from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "mcp"))

from intent_catalog import WORKFLOW_PHASES, WORKFLOWS  # noqa: E402


def command_description(stem: str) -> str:
    path = ROOT / ".kilo" / "commands" / f"{stem}.md"
    if not path.is_file():
        return ""
    text = path.read_text(encoding="utf-8", errors="ignore")
    m = re.match(r"^---\n(.*?)\n---", text, re.S)
    if not m:
        return ""
    for line in m.group(1).splitlines():
        fm = re.match(r"^description:\s*(.*)$", line)
        if fm:
            return fm.group(1).strip()
    return ""


def render() -> str:
    lines: list[str] = [
        "# ROUTER — intent → workflow (auto-generated, do not hand-edit)",
        "",
        "Generated by: `python3 scripts/gen_router.py` (kit: wawoo-skills).",
        "",
        "## Steps (required for agents)",
        "",
        "**For non-trivial requests (code change, research, design, document generation), always call MCP before using tools.**",
        "Substituting the native `skill` tool or a remembered procedure violates this contract.",
        "",
        "1. First choose **one workflow** from the table below (if several apply, prefer the upper row).",
        "2. **Always** call MCP `wawoo-skills_workflow_get` and read the returned steps (no `/name` input; do not wait).",
        "3. Only when you cannot decide, call `wawoo-skills_interpret_intent` with `text` first."
        " If `needs_scoring:true`, pick one from `workflow_catalog` and **re-call in the same turn** with `scoring`.",
        "4. Open only the skills the steps name, via `wawoo-skills_skill_get`. Do not open everything."
        " Use the native `skill` only when MCP is unavailable, and report that.",
        "",
        "## Table",
        "",
        "| workflow | recommended agent | description |",
        "|---|---|---|",
    ]
    for wid in sorted(WORKFLOWS):
        spec = WORKFLOWS[wid]
        desc = command_description(wid) or spec.description
        in_table = desc.replace("|", "/")
        head = in_table[:80]
        in_table = head + "…" if len(in_table) > 80 else head
        lines.append(f"| `{wid}` | {spec.agent} | {in_table} |")
    lines += [
        "",
        "## Phases (decomposition, essentials)",
        "",
        "Get a phase's goal / agent / skills / `mcp_tools_allow` / `exit_criteria` via `workflow_get {name, phase:<id>}`.",
        "Audit workflows (`design-review`, `compliance-review`, `release-review`, `self-review`) have no `implement` → if implementation is needed, **declare the switch**.",
        "",
    ]
    grouped: dict[tuple[str, ...], list[str]] = {}
    for wid in sorted(WORKFLOWS):
        ids = WORKFLOW_PHASES.get(wid, ())
        if ids:
            grouped.setdefault(tuple(ids), []).append(wid)
    for seq, wids in sorted(grouped.items(), key=lambda kv: (-len(kv[0]), kv[0])):
        arrow = " → ".join(f"`{i}`" for i in seq)
        lines.append(f"- {arrow}: {', '.join('`'+w+'`' for w in wids)}")
    lines += [
        "",
        "## Operating gates (hygiene)",
        "",
        "- **Language policy**: code/identifiers = English; engineering records (`plans`, `ACTIVE`, `memory`) and responses = Japanese; explanatory docs = English (primary) + Japanese (secondary). Details: `.kilo/skills/language-policy/SKILL.md`.",
        "- **1 session = 1 target / 1 artifact**. Split independent targets via Task (subagent). Goal: payload < 600KB.",
        "- **Declare a workflow switch in one line** (reason + new workflow) and separate artifacts (do not mix audit and implementation).",
        "- **Converge failures**: fix, or record as a known failure + track (ticket / ACTIVE). Do not leave unconverged `FAILED`.",
        "- **Cleanup**: after tests/runs stop with `docker compose ... down -v` etc. and confirm 0 leftovers via `docker ps`.",
        "- **Memory**: record at least one decision/constraint/gotcha at completion (in the kit, `memory_save`).",
        "- **Token hygiene**: use `grep -n`/`head`/`sed -n`; `/compact` long sessions. One step's output < 4KB.",
        "- **Local verification**: before a PR/publish, run `validate_assets.py` (+ `e2e_flows.py` when applicable) and keep the result.",
        "",
        "## Constraints",
        "",
        "- **SSOT remap**: in a project without the kit's `docs/plans/ACTIVE.md` etc.,"
        "map to that project's existing planning/tracking (do not create `docs/plans/` on your own).",
        "- Write progress to each workflow's SSOT. **memory is for decisions/constraints/gotchas only** (no task-completion logs).",
        "- Stop and get approval for destructive changes, production, external transmission, and publishing.",
        "- This file is auto-generated. Edit `scripts/gen_router.py` instead.",
        "",
    ]
    return "\n".join(lines)


def default_out() -> Path:
    env = os.environ.get("KILO_GLOBAL_DIR", "").strip()
    base = Path(env).expanduser() if env else Path.home() / ".config" / "kilo"
    return base / "ROUTER.md"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", help="output path (default: $KILO_GLOBAL_DIR/ROUTER.md)")
    ap.add_argument("--print", dest="to_stdout", action="store_true", help="just print to stdout")
    args = ap.parse_args()

    text = render()
    if args.to_stdout:
        print(text)
        return 0
    out = Path(args.out).expanduser() if args.out else default_out()
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(f"OK  wrote {out} ({len(text)} bytes, {text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
